from pathlib import Path

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt


def aggregate_measurements(dataframe, components):
    """
    Group repeated measurements at identical stage positions.

    For every StagePosition_m value, calculate:
    - mean
    - standard deviation
    - number of measurements
    - standard error of the mean (SEM)
    """

    aggregation = {}

    for component in components:
        aggregation[component] = ["mean", "std", "count"]

    grouped = (
        dataframe
        .groupby("StagePosition_m")
        .agg(aggregation)
    )

    # Flatten the multi-level column names generated by groupby().agg()
    grouped.columns = [
        f"{component}_{statistic}"
        for component, statistic in grouped.columns
    ]

    grouped = grouped.reset_index()

    # SEM = standard deviation / sqrt(number of measurements)
    for component in components:
        grouped[f"{component}_sem"] = (
            grouped[f"{component}_std"]
            / np.sqrt(grouped[f"{component}_count"])
        )

        # If only one measurement exists at a position, std and SEM are NaN.
        # Set SEM to zero for plotting purposes.
        grouped[f"{component}_sem"] = (
            grouped[f"{component}_sem"].fillna(0)
        )

    return grouped


def compare_magnetic_fields(csv1_path, csv2_path, tolerance=None):
    """
    Compare mean Bx, By, and Bz values from two CSV files.

    Repeated measurements at a given StagePosition_m are grouped and
    averaged before the comparison.

    The plotted quantity is:

        mean(CSV2) - mean(CSV1)

    Error bars represent the propagated standard error of the mean,
    assuming measurements in CSV1 and CSV2 are independent.

    Parameters
    ----------
    csv1_path : str or Path
        Full path to the first CSV file (reference measurement).
    csv2_path : str or Path
        Full path to the second CSV file.
    tolerance : float or None
        Maximum tolerance used to match two StagePosition_m values.
        If None, positions must match exactly.

    Returns
    -------
    pandas.DataFrame
        DataFrame containing mean values, standard deviations, counts,
        SEM values, differences, and propagated uncertainties.
    """

    csv1_path = Path(csv1_path)
    csv2_path = Path(csv2_path)

    components = ["Bx", "By", "Bz"]
    required_columns = ["StagePosition_m", *components]

    # Read the CSV files
    df1 = pd.read_csv(csv1_path)
    df2 = pd.read_csv(csv2_path)

    for filename, dataframe in [(csv1_path.name, df1), (csv2_path.name, df2)]:
        missing_columns = set(required_columns) - set(dataframe.columns)

        if missing_columns:
            raise ValueError(
                f"The file {filename} does not contain the required columns: "
                f"{sorted(missing_columns)}"
            )

    # Keep only relevant columns and sort by stage position
    df1 = df1[required_columns].sort_values("StagePosition_m")
    df2 = df2[required_columns].sort_values("StagePosition_m")

    # Average repeated measurements at each stage position
    summary1 = aggregate_measurements(df1, components)
    summary2 = aggregate_measurements(df2, components)

    if tolerance is None:
        # Exact matching of StagePosition_m values
        comparison = pd.merge(
            summary1,
            summary2,
            on="StagePosition_m",
            how="inner",
            suffixes=("_csv1", "_csv2"),
        )
    else:
        # Nearest-position matching within the specified tolerance
        comparison = pd.merge_asof(
            summary1.sort_values("StagePosition_m"),
            summary2.sort_values("StagePosition_m"),
            on="StagePosition_m",
            direction="nearest",
            tolerance=tolerance,
            suffixes=("_csv1", "_csv2"),
        )

        # Remove unmatched positions
        comparison = comparison.dropna(
            subset=[f"{component}_mean_csv2" for component in components]
        )

    if comparison.empty:
        raise ValueError(
            "No common StagePosition_m values were found between the two files. "
            "Try specifying a tolerance, for example tolerance=1e-6."
        )

    # Calculate mean differences and propagated SEM uncertainties
    for component in components:
        # Difference of means: CSV2 - CSV1
        comparison[f"d{component}"] = (
            comparison[f"{component}_mean_csv2"]
            - comparison[f"{component}_mean_csv1"]
        )

        # Assuming independent measurements:
        #
        # sigma_delta = sqrt(SEM_csv1^2 + SEM_csv2^2)
        comparison[f"d{component}_sem"] = np.sqrt(
            comparison[f"{component}_sem_csv1"] ** 2
            + comparison[f"{component}_sem_csv2"] ** 2
        )

    # Create plots
    fig, axes = plt.subplots(3, 1, figsize=(11, 9), sharex=True)

    colors = ["tab:blue", "tab:orange", "tab:green"]

    for axis, component, color in zip(axes, components, colors):
        axis.errorbar(
            comparison["StagePosition_m"],
            comparison[f"d{component}"],
            yerr=comparison[f"d{component}_sem"],
            fmt="o-",
            markersize=3,
            linewidth=1.2,
            capsize=2,
            color=color,
            label=(
                fr"$\Delta {component} = "
                fr"\overline{{{component}}}_{{CSV2}} - "
                fr"\overline{{{component}}}_{{CSV1}}$"
            ),
        )

        axis.axhline(0, color="black", linewidth=0.8, linestyle="--")
        axis.set_ylabel(f"Δ{component}")
        axis.grid(True, alpha=0.3)
        axis.legend()

    axes[-1].set_xlabel("StagePosition_m (m)")

    fig.suptitle(
        "Magnetic field difference: mean values at each stage position\n"
        f"{csv2_path.name} − {csv1_path.name}"
    )

    plt.tight_layout()
    plt.show()

    return comparison


